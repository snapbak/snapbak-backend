import asyncio
import os

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from conftest import DOWN, POSTGRES, admin, admin_on, alembic, reachable

# A share video's length and size on its upload row, added by 0003 (12 LLD).
SIZE_COLUMNS = (
    "SELECT column_name FROM information_schema.columns"
    " WHERE table_name = 'uploads' AND column_name IN ('duration_ms', 'width', 'height')"
)
# The share's CHECK constraints from 0002, which the models don't declare (12 LLD, Postgres schema).
SHARE_CHECKS = (
    "SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = 'shares'::regclass AND contype = 'c'"
)


def test_cld01_migrations_go_up_down_and_up_and_match_the_models() -> None:
    if not reachable(POSTGRES):
        pytest.skip(DOWN)
    name = f"snapbak_migrate_{os.getpid()}"
    asyncio.run(admin(f"DROP DATABASE IF EXISTS {name}"))
    asyncio.run(admin(f"CREATE DATABASE {name}"))
    url = POSTGRES.rsplit("/", 1)[0].replace("postgresql://", "postgresql+asyncpg://") + f"/{name}"
    config = alembic(url)
    try:
        command.upgrade(config, "head")
        command.downgrade(config, "0002_shares")
        assert asyncio.run(admin_on(url, SIZE_COLUMNS)) == []
        command.upgrade(config, "head")
        assert len(asyncio.run(admin_on(url, SIZE_COLUMNS))) == 3
        checks = {row["def"] for row in asyncio.run(admin_on(url, SHARE_CHECKS))}
        assert {
            "CHECK ((length(slug) >= 16))",
            "CHECK ((length(title) <= 300))",
            "CHECK ((state = ANY (ARRAY['uploading'::text, 'live'::text, 'disabled'::text])))",
        } <= checks, checks
        command.downgrade(config, "base")
        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as drift:
            pytest.fail(f"the migrations and Base.metadata differ: {drift}")
    finally:
        asyncio.run(admin(f"DROP DATABASE {name} WITH (FORCE)"))
